"""限额的默认值：单一事实来源。

单独放一个不依赖任何东西的小模块，是为了避免 ``config`` 与 ``budget``
互相 import：``config`` 读环境变量并以这里的值兜底，``budget`` 只从
``config`` 取最终值。

调这些值时优先用环境变量（见 .env.example），改这里的默认值要同时想清楚
「不配任何环境变量的部署会怎样」。

## 两套额度：游客 vs 注册用户

对外开放的部署里，**未登录的访客是成本风险的主要来源**——他们没有身份成本，
清个 cookie 就能重来。所以游客额度刻意压到"够体验、不够白嫖"：

- 游客：每天 2 万 token（约 3–5 轮对话）、每分钟 3 次、单条消息 200 token（约 400 字）
- 注册用户：现在的默认值（每天 200 万 token 等）

两者都可以用环境变量单独覆盖；把游客额度设成 0 表示**不限**（不推荐），
把 ``GUEST_*`` 设得比注册还高没有意义，但代码不会拦你。
"""

# ---------------------------------------------------------------------------
# 注册用户（也就是「登录之后」的额度）
# ---------------------------------------------------------------------------

#: 每个身份每分钟最多发起多少次对话请求
CHAT_RPM_PER_USER = 8

#: 每个 IP 每分钟的对话请求上限（清 cookie 能换身份，换不掉 IP）
CHAT_RPM_PER_IP = 30

#: 每个身份每天可消耗的 token 总量；0 = 不限
CHAT_DAILY_TOKEN_BUDGET = 2_000_000

#: 单次请求的输入估算上限（token）
CHAT_MAX_INPUT_TOKENS = 60_000

#: 每个 IP 每天可消耗的 token 总量——**游客清 cookie 换身份也绕不过这一层**。
#: 0 = 不限。注册用户的额度不受这一层约束（他们有账号成本）。
GUEST_DAILY_TOKEN_BUDGET_PER_IP = 60_000

# ---------------------------------------------------------------------------
# 游客（未登录）
# ---------------------------------------------------------------------------

#: 游客每天可消耗的 token。2 万大约能问 3–5 轮。
GUEST_DAILY_TOKEN_BUDGET = 20_000

#: 游客每分钟的请求次数（比注册用户更严）
GUEST_RPM_PER_USER = 3

#: 游客单条消息的输入上限（token）。约 400 个汉字——够问清楚问题，
#: 不够把整篇文章丢进来当免费摘要机。
GUEST_MAX_INPUT_TOKENS = 200

# ---------------------------------------------------------------------------
# 模型与 agent
# ---------------------------------------------------------------------------

#: 模型单次回复的输出上限，直接作为 max_tokens 传给模型
AGENT_MAX_OUTPUT_TOKENS = 4_096

#: agent 单次提问允许的图步数上限（一步 ≈ 一次模型调用）
AGENT_RECURSION_LIMIT = 40

# ---------------------------------------------------------------------------
# 沙箱 execute（仅在 ENABLE_CODE_EXECUTION=true 时有意义）
# ---------------------------------------------------------------------------

#: 沙箱 execute：每个 org 每分钟的执行次数
EXECUTE_RPM_PER_ORG = 60

#: 沙箱 execute：单次执行时长硬上限（秒）
EXECUTE_TIMEOUT_MAX = 300

# ---------------------------------------------------------------------------
# 账号
# ---------------------------------------------------------------------------

#: 用户名长度与字符集（字母/数字/下划线/连字符；大小写不敏感地唯一）
USERNAME_MIN_LEN = 3
USERNAME_MAX_LEN = 32

#: 密码最短长度
PASSWORD_MIN_LEN = 8

#: PBKDF2 迭代次数。60 万是 OWASP 对 PBKDF2-HMAC-SHA256 的现行建议量级；
#: 单次校验约几十毫秒，登录接口的频率下完全可接受。
PBKDF2_ITERATIONS = 600_000

#: 登录会话有效期（秒）。默认 30 天。
SESSION_TTL_SECONDS = 30 * 24 * 3600
